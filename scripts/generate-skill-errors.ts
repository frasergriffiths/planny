// Generate the skill's error reference from the server's code registry.
// Run: bun run scripts/generate-skill-errors.ts
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { ERROR_CODES, type ErrorRetry } from '../src/error-codes.js';

const out = join(import.meta.dir, '..', 'skills', 'planny', 'reference', 'errors.md');

function retryText(retry: ErrorRetry): string {
  if (retry === 'retry-after') return 'Retry-After header';
  if (retry === 'reset-date') return 'Reset date in the message';
  if (retry === 'retry-after-and-reset-date') return 'Retry-After header and reset date';
  return 'None';
}

function responseText(response: 'json' | 'page' | 'both'): string {
  if (response === 'both') return 'Page or JSON';
  if (response === 'page') return 'Page';
  return 'JSON';
}

function cell(value: string): string {
  return value.replaceAll('|', '\\|').replaceAll('\n', ' ');
}

const rows = ERROR_CODES.map((entry) => [
  String(entry.status),
  `\`${entry.code}\``,
  entry.scope,
  entry.when,
  retryText(entry.retry),
  responseText(entry.response),
  entry.notes ?? '',
].map(cell).join(' | '));

const body = `# Error reference

Generated from \`src/error-codes.ts\` by \`scripts/generate-skill-errors.ts\`. Do not edit this file by hand. Run \`bun run scripts/generate-skill-errors.ts\` after changing the registry.

| Status | Code | Scope | When | Retry or reset | Response | Notes |
|---|---|---|---|---|---|---|
${rows.map((row) => `| ${row} |`).join('\n')}

## Reading the table

- Upload and delete calls return JSON. The body is \`{"error":{"code":"...","message":"..."}}\`.
- Plan views return a page for the reader, not JSON. The page says what happened and what to do next.
- \`planny_not_configured\` is a configuration failure, not a pause. It has no \`Retry-After\`, and the page does not name the missing variable. The server log does.
- The monthly read and upload guards use a reset date. The page or message names it. \`Retry-After\`, where present, carries seconds, not a date.
- The stored guards, \`storage_full\` and \`storage_limit\`, have no reset date. Deleting or expiring plans frees the space.
- The 4 MiB cap is 4,194,304 bytes on the raw body, inclusive. The sanitiser can add a wrapper, so a fragment right at the cap can still be rejected.
- A plan link with a query string is a 404 and does not count as a read.
`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, body, 'utf8');
console.log(`wrote ${out} (${ERROR_CODES.length} codes)`);

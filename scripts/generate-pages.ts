#!/usr/bin/env bun
// Embed the built static entries in a TS module, so the function never reads dist at runtime.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dir, '..');
const read = (name: string) => readFileSync(join(root, 'dist', name), 'utf8');
const pages = {
  home: read('index.html'),
  notFound: read('404.html'),
  gone: read('410.html'),
  paused: read('503.html'),
  terms: read('terms.html'),
  sample: readFileSync(join(root, 'public', 'sample', 'index.html'), 'utf8'),
  robots: readFileSync(join(root, 'public', 'robots.txt'), 'utf8'),
  sitemap: readFileSync(join(root, 'public', 'sitemap.xml'), 'utf8'),
};
const body = `// Generated by scripts/generate-pages.ts from the Vite build. Do not edit.\nexport const PAGES = ${JSON.stringify(pages, null, 2)} as const;\n`;
writeFileSync(join(root, 'src', 'generated-pages.ts'), body);
console.log('wrote src/generated-pages.ts');
